## Questions of Interests
We want to find out if the actual proportion of red M&Ms in a pack of M&Ms aligns with the theoretical proportion of red M&Ms given by the M&M company. 

Dataset link: 
- [M&M distribution summary dataset](https://joshmadison.com/2007/12/02/mms-color-distribution-analysis/)
- [M&M individual distribution by pack dataset](https://joshmadison.com/2007/12/02/mms-color-distribution-analysis-individual-pack-data/)

### Data Description
The data was collected by Josh Madison. He got a box of M&M with 48 packages and counted the total number of M&Ms and the color in each pack. The key variable we will be using is the observed proportion of red M&Ms (observed number of red M&Ms in pack divided by observed total number of M&Ms in pack). Since the dataset we found is a summary table, we will only use the red M&M count and total count for our analysis, disregarding the counts of the other colors. Each row in the selected dataset represents one pack of M&Ms. The larger population that we are sampling from is all the producted M&M packs.

### Outline of The Graph
We will create a histogram with the proportions of red M&Ms per pack within our sample on the x-axis.

### Inference Method
Our inference will be on a single population proportion.
