## Questions of Interests
We want to find out if the actual proportion of red M&Ms in a pack of M&Ms aligns with the theoretical proportion of red M&Ms given by the M&M company. 

Dataset link: 
- [M&M distribution dataset](https://joshmadison.com/2007/12/02/mms-color-distribution-analysis/)
- [M&M individual distribution by pack dataset](https://joshmadison.com/2007/12/02/mms-color-distribution-analysis-individual-pack-data/)

### Data Description
The data was collected by Josh Madison. He got a box of M&M with 48 packages and counted the total number of M&Ms and the color in each pack. The key variable we will be using is the red M&Ms observed quantity. Since the dataset we found is a summary table, we will select the red M&M count for our analysis. Each row in the selected dataset means the observed count of red M&Ms in a pack. The larger population of our sample is all the producted M&M packs.

